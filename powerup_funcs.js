// create a new single shell projectile
export function build_bomb_projectile_throw(kart)
{
  let mesh
  mesh = build_bomb_projectile()
  mesh.name = "bomb projectile"
  mesh.userData["collision_type"] = collision_funcs.type.PROJECTILE
  mesh.position.z = 0.5
  mesh.scale.x = 3; mesh.scale.y = 3; mesh.scale.z = 3
  // append the relevant translation data
  mesh.position.x = kart.position.x - (4 * Math.cos(kart.rotation.z + Math.PI / 2))
  mesh.position.y = kart.position.y - (4 * Math.sin(kart.rotation.z + Math.PI / 2))
  mesh.rotation.z = kart.rotation.z
  let velocity = kart_funcs.get_last_velocity()
  if (velocity < 0) mesh.userData["last_velocity"] = 0
  else mesh.userData["last_velocity"] = velocity / 2
  mesh.userData["time"] = 0
  //~ mesh.add(new three.PointLight(0xA0A0A0, 10, 1000))
  return mesh
}


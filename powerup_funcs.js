// create a new single shell projectile
export function build_single_projectile()
{
  let mesh, geometry, material
  geometry = new three.BufferGeometry()
  geometry.setAttribute("position", new three.BufferAttribute(single_projectile_vertices, 3))
  geometry.computeVertexNormals()
  material = new three.MeshStandardMaterial({color: 0x00F0F0})
  mesh = new three.Mesh(geometry, material)
  mesh.castShadow = true
  return mesh
}

// create a new single shell projectile
export function build_single_projectile_throw(kart)
{
  // build the projectile
  let mesh
  mesh = build_single_projectile()
  mesh.name = "single projectile"
  mesh.userData["collision_type"] = collision_funcs.type.PROJECTILE
  mesh.position.z = 0.5
  mesh.scale.x = 3; mesh.scale.y = 3; mesh.scale.z = 3
  // append the relevant translation data
  mesh.position.x = kart.position.x + (2 * Math.cos(kart.rotation.z + Math.PI / 2))
  mesh.position.y = kart.position.y + (2 * Math.sin(kart.rotation.z + Math.PI / 2))
  mesh.rotation.z = kart.rotation.z
  let velocity = kart_funcs.get_last_velocity()
  if (velocity < 0) mesh.userData["last_velocity"] = 0
  else mesh.userData["last_velocity"] = velocity
  return mesh
}

// parabole
function parabole(time)
{
  return - (0.25 * Math.pow(time - 4.4, 2)) + 6
}

// update the speed of a projectile
const max_projectile_velocity = 0.8
const time_dif = 0.3
export function update_single_projectile_vel(proyectile)
{
  // update the velocity and add the position difference
  // linear
  if (proyectile.name == "single projectile") {
    if (proyectile.userData["last_velocity"] < max_projectile_velocity)
      proyectile.userData["last_velocity"] += 0.1
    else if (proyectile.userData["last_velocity"] > max_projectile_velocity)
      proyectile.userData["last_velocity"] -= 0.1
    proyectile.position.x += proyectile.userData["last_velocity"] * Math.cos(proyectile.rotation.z + Math.PI / 2)
    proyectile.position.y += proyectile.userData["last_velocity"] * Math.sin(proyectile.rotation.z + Math.PI / 2)
  }
  // parabolic
  else if (proyectile.name == "bomb projectile") {
    // change the color
    if (proyectile.material.color.r < 0.99) proyectile.material.color.r += 0.001
    if (proyectile.material.color.b > 0) proyectile.material.color.b -= 0.001
    if (proyectile.material.color.g > 0) proyectile.material.color.g -= 0.001
    proyectile.material.emissive.r += 0.005
    // update velocity
    if (proyectile.userData["last_velocity"] > 0.5) proyectile.userData["last_velocity"] = 0.5
    else proyectile.userData["last_velocity"] += 0.1
    // change height
    if (proyectile.userData["time"] < 8.4) {
      proyectile.userData["time"] += 0.1
      proyectile.position.x += proyectile.userData["last_velocity"]
                               * Math.cos(proyectile.rotation.z + Math.PI / 2)
      proyectile.position.y += proyectile.userData["last_velocity"]
                               * Math.sin(proyectile.rotation.z + Math.PI / 2)
      proyectile.position.z = parabole(proyectile.userData["time"])
    } else {
      proyectile.scale.x += 0.05
      proyectile.scale.y += 0.05
      proyectile.scale.z += 0.05
    }
  }
}


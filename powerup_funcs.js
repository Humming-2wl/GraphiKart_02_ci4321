// create hammer powerup
export function build_hammer()
{
  // hammer handle
  let mesh, geometry, material
  geometry = new three.BufferGeometry()
  geometry.setAttribute("position", new three.BufferAttribute(hammer_handle_vertices, 3))
  geometry.setAttribute("uv", new three.BufferAttribute(hammer_handle_uv, 2))
  geometry.computeVertexNormals()
  let tex, normal
  tex = (new three.TextureLoader()).load("images/wood.png")
  tex.colorSpace = three.SRGBColorSpace
  normal = (new three.TextureLoader()).load("images/wood_normalmap.png")
  normal.colorSpace = three.SRGBColorSpace
  material = new three.MeshStandardMaterial({map: tex, normalMap: normal})
  material.emissive = new three.Color(0.01, 0.01, 0.01)
  mesh = new three.Mesh(geometry, material)
  
  // hammer head
  geometry = new three.BufferGeometry()
  geometry.setAttribute("position", new three.BufferAttribute(hammer_head_vertices, 3))
  geometry.setAttribute("uv", new three.BufferAttribute(hammer_head_uv, 2))
  geometry.computeVertexNormals()
  tex = (new three.TextureLoader()).load("images/metal.png")
  tex.colorSpace = three.SRGBColorSpace
  normal = (new three.TextureLoader()).load("images/metal_normalmap.png")
  normal.colorSpace = three.SRGBColorSpace
  material = new three.MeshStandardMaterial({map: tex, normalMap: normal})
  material.emissive = new three.Color(0.01, 0.01, 0.01)
  mesh.add(new three.Mesh(geometry, material))
  mesh.children[0].userData["collision_type"] = collision_funcs.type.PROJECTILE
  
  // done!
  return mesh
}
